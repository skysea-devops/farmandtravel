// Yerelleştirilmiş, alfabetik sıralı ülke adları. Türkiye en üstte, sonra
// alfabetik. "Diğer/Other" çağıran taraf ekler (listede yoksa / belirtmek istemeyen).
export function countryNames(lang: string): string[] {
  const name = (c: Country) => (lang === "en" ? c.en : c.tr);
  const loc = lang === "en" ? "en" : "tr";
  const rest = COUNTRIES.filter((c) => c.tr !== "Türkiye").map(name).sort((a, b) => a.localeCompare(b, loc));
  const tr = COUNTRIES.find((c) => c.tr === "Türkiye")!;
  return [name(tr), ...rest];
}
